const root = document.documentElement;
const themeToggles = document.querySelectorAll('[data-theme-toggle]');
const localeToggles = document.querySelectorAll('[data-locale-toggle]');
const mobileMenu = document.querySelector('[data-mobile-menu]');
const menuToggle = document.querySelector('[data-menu-toggle]');
const menuOpenIcon = document.querySelector('[data-menu-open]');
const menuCloseIcon = document.querySelector('[data-menu-close]');
const heroCarousel = document.querySelector('[data-hero-carousel]');

let locale = localStorage.locale === 'bn' ? 'bn' : 'en';

function updateThemeControls() {
    const isDark = root.classList.contains('dark');

    document.querySelectorAll('[data-theme-sun]').forEach((icon) => {
        icon.classList.toggle('hidden', isDark);
    });

    document.querySelectorAll('[data-theme-moon]').forEach((icon) => {
        icon.classList.toggle('hidden', !isDark);
    });

    themeToggles.forEach((button) => {
        button.setAttribute('aria-label', isDark ? 'Use light theme' : 'Use dark theme');
    });
}

function applyLocale(nextLocale) {
    locale = nextLocale;
    localStorage.locale = locale;
    root.lang = locale;
    root.dir = 'ltr';

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;

        if (translations[locale][key]) {
            element.textContent = translations[locale][key];
        }
    });

    document.querySelectorAll('[data-locale-label]').forEach((label) => {
        label.textContent = locale === 'en' ? 'বাং' : 'EN';
    });

    localeToggles.forEach((button) => {
        button.setAttribute('aria-label', locale === 'en' ? 'বাংলা ভাষা ব্যবহার করুন' : 'Use English language');
    });
}

function setMenuState(isOpen) {
    if (!mobileMenu || !menuToggle) {
        return;
    }

    mobileMenu.hidden = !isOpen;
    menuToggle.setAttribute('aria-expanded', String(isOpen));
    menuToggle.setAttribute('aria-label', isOpen ? 'Close menu' : 'Open menu');
    menuOpenIcon?.classList.toggle('hidden', isOpen);
    menuCloseIcon?.classList.toggle('hidden', !isOpen);
    document.body.classList.toggle('overflow-hidden', isOpen);
}

themeToggles.forEach((button) => {
    button.addEventListener('click', () => {
        root.classList.toggle('dark');
        localStorage.theme = root.classList.contains('dark') ? 'dark' : 'light';
        updateThemeControls();
    });
});

localeToggles.forEach((button) => {
    button.addEventListener('click', () => {
        applyLocale(locale === 'en' ? 'bn' : 'en');
    });
});

menuToggle?.addEventListener('click', () => {
    setMenuState(mobileMenu.hidden);
});

mobileMenu?.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => setMenuState(false));
});

